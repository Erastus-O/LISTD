"""Admin adds a Pro (first name + email) -> invitation code/link -> Pro accepts via link, verifies with code + email,
creates a password and lands in onboarding. Also: wrong code, wrong email, resend invalidates old code, cancel."""
import os, re
from playwright.sync_api import sync_playwright
HERE = os.path.dirname(os.path.abspath(__file__))
APP = 'file://' + os.path.join(HERE, '..', 'dist', 'listd-platform.html')
OUT = os.path.join(HERE, 'out', 'shots') + '/'; os.makedirs(OUT, exist_ok=True)
res = []; errs = []
def check(ok, m): res.append((ok, m)); print(('PASS ' if ok else 'FAIL ') + m, flush=True)
with sync_playwright() as pw:
    br = pw.chromium.launch(); ctx = br.new_context(viewport={'width': 1280, 'height': 860}); p = ctx.new_page()
    p.on('pageerror', lambda e: errs.append(str(e)))
    W = lambda ms=300: p.wait_for_timeout(ms)
    err = lambda: (p.locator('#au-err').text_content() or '') if p.locator('#au-err').count() else ''
    p.goto(APP); W(600)
    p.click('[data-act=role][data-r=admin]'); W()
    p.fill('#au-name', 'Ops'); p.fill('#au-email', 'ops@listd.test'); p.fill('#au-password', 'Admin2026!'); p.fill('#au-confirm', 'Admin2026!')
    p.click('form[data-form=auth-admin-setup] button[type=submit]'); W(1200)
    p.fill('#au-code', p.evaluate("() => totp(S.auth.secret)")); p.click('form[data-form=auth-mfa-setup] button[type=submit]'); W(900)
    p.click('.a-side [data-go=pros]'); W()
    p.click('.a-head [data-act=pro-add]'); W(); p.screenshot(path=OUT + 'i1-add.png')
    p.fill('#pi-first', 'Tunde'); p.fill('#pi-email', 'Tunde.Bello@Example.test'); p.click('form[data-form=pro-invite] button[type=submit]'); W(600)
    code = p.locator('#inv-code').text_content(); link = p.locator('#inv-link').text_content(); p.screenshot(path=OUT + 'i2-ready.png')
    href = p.locator('.a-modal a[href^=mailto]').get_attribute('href')
    check(bool(re.match(r'^[A-Z0-9]{4}-[A-Z0-9]{4}$', code)) and link.endswith('#invite=' + code), 'code and link generated: ' + code)
    check('tunde.bello%40example.test' in href.lower() and code in href.replace('%2D', '-'), 'email draft addressed to the Pro with the code')
    check(p.evaluate("() => { var x = Object.values(D.pros)[0]; return x.status === 'INVITED' && !!x.invite.hash && JSON.stringify(x).indexOf('" + code + "') < 0; }"), 'only a hash of the code is stored')
    p.click('.a-modal [data-act=close]'); W()
    hdr = p.locator('.a-clip thead th').all_inner_texts()
    check(hdr[1].lower() == 'email' and hdr[-1].lower() == 'status', 'table: Email column, Status last ' + str(hdr))
    check('Invited' in p.locator('.a-clip tbody tr').first.inner_text(), 'row shows Invited'); p.screenshot(path=OUT + 'i3-table.png')
    # resend makes old code invalid
    p.locator('.a-clip tbody tr').first.click(); W(); p.screenshot(path=OUT + 'i4-detail.png', full_page=True)
    p.click('[data-act=pro-resend]'); W(600); code2 = p.locator('#inv-code').text_content(); p.click('.a-modal [data-act=close]'); W()
    check(code2 != code, 'resend creates a new code')
    # Pro opens the invitation link (same browser storage, new tab)
    q = ctx.new_page(); q.on('pageerror', lambda e: errs.append(str(e)))
    q.goto(APP + '#invite=' + code2); q.wait_for_timeout(800)
    p = q; W = lambda ms=300: q.wait_for_timeout(ms)
    check(p.evaluate('S.role') == 'pro' and p.input_value('#au-code') == code2, 'link opens Pro invitation screen with the code filled in'); p.screenshot(path=OUT + 'i5-accept.png')
    p.fill('#au-code', code); p.fill('#au-email', 'tunde.bello@example.test'); p.fill('#au-password', 'Listd2026!'); p.click('form[data-form=auth-invite] button[type=submit]'); W(900)
    check('isn’t valid' in err(), 'old code rejected: ' + err())
    p.fill('#au-code', code2); p.fill('#au-email', 'someone@else.test'); p.fill('#au-password', 'Listd2026!'); p.click('form[data-form=auth-invite] button[type=submit]'); W(900)
    check('email address your invitation' in err(), 'wrong email rejected')
    p.fill('#au-email', 'tunde.bello@example.test'); p.fill('#au-password', 'Listd2026!'); p.click('form[data-form=auth-invite] button[type=submit]'); W(1500)
    st = p.evaluate("() => { var x = Object.values(D.pros)[0]; return [S.proId === x.id, x.status, !!x.emailVerifiedAt, x.invite.hash]; }")
    check(st == [True, 'DRAFT', True, None], 'accepted: signed in, onboarding, email verified ' + str(st))
    check(p.input_value('#pr-name') == 'Tunde', 'onboarding opens at About you with first name filled'); p.screenshot(path=OUT + 'i6-onboarding.png')
    # signs in again later with the new password
    p.click('.a-top [data-act=signout]') if p.locator('.a-top [data-act=signout]').count() else p.evaluate('signOut()'); W()
    p.fill('#au-email', 'tunde.bello@example.test'); p.fill('#au-password', 'Listd2026!'); p.click('form[data-form=auth-signin] button[type=submit]'); W(1500)
    check(p.evaluate('!!S.proId'), 'Pro can sign in with the password they created')
    # cancel an invitation
    a = ctx.new_page(); a.goto(APP); a.wait_for_timeout(700); a.click('[data-act=role][data-r=admin]'); a.wait_for_timeout(300)
    a.fill('#au-email', 'ops@listd.test'); a.fill('#au-password', 'Admin2026!'); a.click('form[data-form=auth-signin] button[type=submit]'); a.wait_for_timeout(1200)
    a.fill('#au-code', a.evaluate("() => totp(AUTH.accounts.find(x => x.role === 'admin').mfa.secret)")); a.click('form[data-form=auth-mfa] button[type=submit]'); a.wait_for_timeout(900)
    r = a.evaluate("async () => { var x = await cmdInvitePro('Kemi', 'kemi@example.test'); cmdCancelInvite(x.id); return [D.pros[x.id].status, proStatusLabel(D.pros[x.id])]; }")
    check(r == ['REJECTED', 'Invite cancelled'], 'cancel invitation ' + str(r))
    print('FAILS', [m for ok, m in res if not ok]); print('ERRORS', errs); br.close()
